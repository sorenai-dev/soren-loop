// Generates src/normalize/unicode-15.1-assigned.ts from the checked-in UCD 15.1
// DerivedGeneralCategory.txt. "Assigned" means any general category except Cn (RFC 04 §3.1
// step 2). Run with: pnpm --filter @sorenai/loop-schema gen:unicode
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const UCD_FILE = 'DerivedGeneralCategory-15.1.0.txt'
// SHA-256 of the file as served from https://www.unicode.org/Public/15.1.0/ucd/extracted/
export const UCD_SHA256 = '760720ac034f96b630a3055879a744e0907184e8aa811e89ba34583a7a487e85'

type Range = [number, number]

const MAX_CODE_POINT = 0x10ffff
const CN_LINE = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*Cn\b/

function unassignedRanges(ucdText: string): Range[] {
  const ranges: Range[] = []
  for (const line of ucdText.split('\n')) {
    const m = CN_LINE.exec(line)
    if (m?.[1] !== undefined) ranges.push([parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16)])
  }
  return ranges.sort((a, b) => a[0] - b[0])
}

function assignedRanges(ucdText: string): Range[] {
  const assigned: Range[] = []
  let next = 0
  for (const [start, end] of unassignedRanges(ucdText)) {
    if (start > next) assigned.push([next, start - 1])
    next = Math.max(next, end + 1)
  }
  if (next <= MAX_CODE_POINT) assigned.push([next, MAX_CODE_POINT])
  return assigned
}

const hex = (n: number): string => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`

export function generateTable(ucdText: string): string {
  const ranges = assignedRanges(ucdText)
  const rows: string[] = []
  for (let i = 0; i < ranges.length; i += 4) {
    rows.push(`  ${ranges.slice(i, i + 4).map(([s, e]) => `[${hex(s)}, ${hex(e)}]`).join(', ')},`)
  }
  return [
    `// Generated by scripts/gen-unicode-table.ts from ${UCD_FILE}. Do not edit.`,
    '// Inclusive code point ranges whose general category is not Cn in Unicode 15.1.',
    'export const ASSIGNED_RANGES: readonly (readonly [number, number])[] = [',
    ...rows,
    ']',
    '',
  ].join('\n')
}

/** Verifies the UCD bytes against the pin, then writes the table. Throws (writing nothing) on a mismatch. */
export function writeTable(ucd: Uint8Array, out: string | URL): void {
  const digest = createHash('sha256').update(ucd).digest('hex')
  if (digest !== UCD_SHA256) {
    throw new Error(`${UCD_FILE}: SHA-256 ${digest} does not match the pin ${UCD_SHA256}`)
  }
  writeFileSync(out, generateTable(new TextDecoder().decode(ucd)))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    writeTable(
      readFileSync(new URL(`./data/${UCD_FILE}`, import.meta.url)),
      new URL('../src/normalize/unicode-15.1-assigned.ts', import.meta.url),
    )
  } catch (error) {
    console.error((error as Error).message)
    process.exit(1)
  }
}
